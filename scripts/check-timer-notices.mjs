/** Timer endings away from Focus, remembered-duration wording and short-lived
 * success messages, on an installed page clock with its own storage. */
export async function checkTimerNotices(browser, url, check) {
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  try {
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    page.setDefaultTimeout(6000)
    await page.clock.install({ time: new Date('2026-11-03T12:00:00+08:00') })
    await page.goto(url)
    const button = (name, within = page) => within.getByRole('button', { name, exact: true })
    const session = () => page.evaluate(() => JSON.parse(localStorage.getItem('whale-focus:snapshot'))?.timer.session)
    const banner = page.locator('.timer-ended')
    const live = page.locator('.app > [aria-live]')
    const tab = name => page.locator('.tab-bar').getByRole('button', { name, exact: true })
    const expire = async () => {
      const { durationMs } = await session()
      await page.clock.fastForward(durationMs + 100)
      await page.clock.runFor(300)
    }

    await button('开始专注').waitFor()
    await page.evaluate(() => navigator.serviceWorker.ready)
    await button('查看状态').waitFor()
    await page.clock.runFor(10_100)
    await button('查看状态').waitFor({ state: 'detached' })
    check('The offline-ready note leaves on its own', true)
    check('The duration hint says tapping the time adjusts it', await page.locator('.fp-hold-hint').innerText() === '点时间可调时长')
    check('The time shows an edit mark', await page.locator('.fp-clock-trigger .fp-clock-edit').count() === 1)
    await page.getByRole('button', { name: /^调整专注时长/ }).click()
    const dial = page.getByRole('dialog', { name: '调专注时长' })
    await dial.getByText('开始后，下次沿用这个时长').waitFor()
    await page.setViewportSize({ width: 320, height: 568 })
    const apply = await button('用这个时长', dial).boundingBox()
    const nav = await page.locator('.tab-bar').boundingBox()
    check('The dial keeps its apply button clear of navigation at 320x568', apply.y + apply.height <= nav.y)
    await page.setViewportSize({ width: 375, height: 812 })
    await dial.locator('#custom-minutes').fill('1')
    await button('用这个时长', dial).click()

    await button('开始专注').click()
    await button('暂停专注').waitFor()
    await tab('记录').click()
    const page0 = await page.evaluate(() => [document.scrollingElement.scrollHeight, document.querySelector('.tab-bar').getBoundingClientRect().y])
    await expire()
    await banner.waitFor()
    check('A focus ending on Records shows the result and its save state', (await banner.innerText()).includes('这一段计时结束了') && (await banner.innerText()).includes('已保存'))
    check('The ending reaches the shared live region', (await live.innerText()).includes('这一段计时结束了'))
    check('The tab title names the ending', await page.title() === '专注结束 — Whale Focus')
    const page1 = await page.evaluate(() => [document.scrollingElement.scrollHeight, document.querySelector('.tab-bar').getBoundingClientRect().y])
    check('The banner does not move the page', page0.every((value, i) => Math.abs(value - page1[i]) <= 1))
    await button('查看结果', banner).click()
    await button('开始休息').waitFor()
    check('Viewing the result opens Focus', await page.locator('.app').getAttribute('data-screen') === 'home')
    await tab('记录').click()
    check('An ending already seen on Focus is not announced again', !await banner.count())
    await page.clock.runFor(300)
    check('The title stops naming a seen ending away from Focus', await page.title() === 'Whale Focus')
    await tab('专注').click()

    await button('开始休息').click()
    await button('暂停休息').waitFor()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await expire()
    await banner.waitFor()
    check('A rest ending on Settings offers a return without starting anything', (await banner.innerText()).includes('休息计时结束了') && await button('回到专注', banner).isVisible() && !await session())
    await button('知道了', banner).click()
    check('Dismissing leaves the reader on the same screen', !await banner.count() && await page.locator('.app').getAttribute('data-screen') === 'settings')
    check('Settings explains how a Focus choice carries over', (await page.locator('.settings').innerText()).includes('专注页调过的时长会沿用到下次'))
    await button('‹ 回到专注').click()

    const note = page.locator('.fp-note')
    const details = button('查看状态')
    await button('留个标记').click()
    await button('撤销标记', note).waitFor()
    check('A saved mark needs no details button', !await details.count())
    await page.clock.runFor(10_100)
    await button('撤销标记', note).waitFor({ state: 'detached' })
    check('A saved mark and its shortcuts leave after ten seconds', (await note.innerText()).trim() === '')

    await button('留个标记').click()
    await button('撤销标记', note).focus()
    await page.clock.runFor(10_100)
    check('A shortcut with keyboard focus stays', await button('撤销标记', note).isVisible())
    await button('开始专注').focus()
    await page.clock.runFor(10_100)
    await button('撤销标记', note).waitFor({ state: 'detached' })
    check('It leaves once focus moves on', true)

    await page.evaluate(() => {
      window.originalSetItem = Storage.prototype.setItem
      Storage.prototype.setItem = function (name, value) {
        if (name === 'whale-focus:snapshot') throw new DOMException('Injected quota failure', 'QuotaExceededError')
        return window.originalSetItem.call(this, name, value)
      }
    })
    await button('留个标记').click()
    await details.waitFor()
    await page.clock.runFor(10_100)
    check('A failed save stays with its details', await details.isVisible() && (await note.innerText()).trim() !== '')
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem })
    check('Timer notices produce no unexpected browser errors', errors.filter(text => !text.includes('Injected quota')).length === 0)
  } finally { await context.close() }
}
