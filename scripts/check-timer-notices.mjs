/** Timer endings away from Focus, remembered-duration wording and short-lived
 * success messages, on an installed page clock with its own storage. */
export async function checkTimerNotices(browser, url, check) {
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  try {
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    page.setDefaultTimeout(6000)
    await page.clock.install({ time: new Date('2026-11-03T12:00:00+08:00') })
    await page.goto(url)
    const button = (name, within = page) => within.getByRole('button', { name, exact: true })
    const session = () => page.evaluate(() => JSON.parse(localStorage.getItem('whale-focus:snapshot'))?.timer.session)
    const banner = page.locator('.timer-ended')
    const live = page.locator('.app > [aria-live]')
    const tab = name => page.locator('.tab-bar').getByRole('button', { name, exact: true })
    const expire = async () => {
      const { durationMs } = await session()
      await page.clock.fastForward(durationMs + 100)
      await page.clock.runFor(300)
    }

    await button('开始专注').waitFor()
    await page.evaluate(() => navigator.serviceWorker.ready)
    await button('查看状态').waitFor()
    await page.clock.runFor(10_100)
    await button('查看状态').waitFor({ state: 'detached' })
    check('The offline-ready note leaves on its own', true)
    check('The time shows an edit mark', await page.locator('.fp-clock-trigger .fp-clock-edit').count() === 1)
    await page.locator('.fp-clock-edit').click()
    await page.getByRole('dialog', { name: '调专注时长' }).waitFor()
    await page.keyboard.press('Escape')
    await page.getByRole('dialog', { name: '调专注时长' }).waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: /^调整专注时长/ }).click()
    const dial = page.getByRole('dialog', { name: '调专注时长' })
    await dial.getByText('开始后，下次沿用这个时长').waitFor()
    await page.setViewportSize({ width: 320, height: 568 })
    const apply = await button('用这个时长', dial).boundingBox()
    const nav = await page.locator('.tab-bar').boundingBox()
    check('The dial keeps its apply button clear of navigation at 320x568', apply.y + apply.height <= nav.y)
    await page.setViewportSize({ width: 375, height: 812 })
    await dial.locator('#custom-minutes').fill('1')
    await button('用这个时长', dial).click()

    await button('开始专注').click()
    await button('暂停专注').waitFor()
    await tab('记录').click()
    const page0 = await page.evaluate(() => [document.scrollingElement.scrollHeight, document.querySelector('.tab-bar').getBoundingClientRect().y])
    await expire()
    await banner.waitFor()
    check('A focus ending on Records shows the result and its save state', (await banner.innerText()).includes('这一段计时结束了') && (await banner.innerText()).includes('已保存'))
    check('The ending reaches the shared live region', (await live.innerText()).includes('这一段计时结束了'))
    check('The tab title names the ending', await page.title() === '专注结束 — Whale Focus')
    const page1 = await page.evaluate(() => [document.scrollingElement.scrollHeight, document.querySelector('.tab-bar').getBoundingClientRect().y])
    check('The banner does not move the page', page0.every((value, i) => Math.abs(value - page1[i]) <= 1))
    await button('查看结果', banner).click()
    await button('开始休息').waitFor()
    check('Viewing the result opens Focus', await page.locator('.app').getAttribute('data-screen') === 'home')
    await tab('记录').click()
    check('An ending already seen on Focus is not announced again', !await banner.count())
    await page.clock.runFor(300)
    check('The title stops naming a seen ending away from Focus', await page.title() === 'Whale Focus')
    await tab('专注').click()

    await button('开始休息').click()
    await button('暂停休息').waitFor()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await expire()
    await banner.waitFor()
    check('A rest ending on Settings offers a return without starting anything', (await banner.innerText()).includes('休息计时结束了') && await button('回到专注', banner).isVisible() && !await session())
    await button('知道了', banner).click()
    check('Dismissing leaves the reader on the same screen', !await banner.count() && await page.locator('.app').getAttribute('data-screen') === 'settings')
    check('Settings explains how a Focus choice carries over', (await page.locator('.settings').innerText()).includes('专注页调过的时长会沿用到下次'))
    await button('‹ 回到专注').click()

    const note = page.locator('.fp-note')
    const details = button('查看状态')
    const noteText = note.locator('.fp-note__text')
    await button('留个标记').click()
    await button('撤销标记', note).waitFor()
    check('A saved mark needs no details button', !await details.count())
    await page.clock.runFor(10_100)
    await noteText.getByText('已记下一个标记。').waitFor({ state: 'detached' })
    check('The message fades while its mark shortcuts stay', await button('撤销标记', note).isVisible() && await button('补充文字', note).isVisible())

    await button('撤销标记', note).click()
    const restore = button('撤销删除：空标记', note)
    await restore.waitFor()
    await page.evaluate(() => document.activeElement?.blur())
    await page.clock.runFor(10_100)
    await noteText.getByText('已删除。').waitFor({ state: 'detached' })
    check('Undoing a mark keeps its named restore after the message fades', await restore.isVisible())
    await restore.focus()
    await page.keyboard.press('Enter')
    await restore.waitFor({ state: 'detached' })
    check('Keyboard focus survives the restore button going away', await page.evaluate(() => document.activeElement.innerText.includes('留个标记')))
    check('The named restore brings the mark back', (await page.evaluate(() => JSON.parse(localStorage.getItem('whale-focus:snapshot')).thoughts)).filter(t => t.deletedAt === null).length >= 1)
    await page.clock.runFor(10_100)

    await button('留个标记').click()
    await button('撤销标记', note).waitFor()
    await button('开始专注').click()
    await button('暂停专注').waitFor()
    await button('撤销标记', note).waitFor({ state: 'detached' })
    check('A new session retires the earlier mark shortcuts', !await button('补充文字', note).count())
    await button('结束专注').click()
    await button('确认结束', page.getByRole('dialog')).click()
    await button('准备专注').click()
    await page.clock.runFor(10_100)

    await tab('记录').click()
    await button('只看想法').click()
    await page.locator('.record-summary').first().click()
    await button('删除这条想法').click()
    await page.locator('.records-feedback').getByRole('button', { name: /^撤销删除/ }).waitFor()
    await tab('专注').click()
    check('A deletion made on Records offers no restore on Focus', !await note.getByRole('button', { name: /^撤销删除/ }).count())

    await page.evaluate(() => {
      window.originalSetItem = Storage.prototype.setItem
      Storage.prototype.setItem = function (name, value) {
        if (name === 'whale-focus:snapshot') throw new DOMException('Injected quota failure', 'QuotaExceededError')
        return window.originalSetItem.call(this, name, value)
      }
    })
    await button('留个标记').click()
    await details.waitFor()
    await page.clock.runFor(10_100)
    check('A failed save stays with its details', await details.isVisible() && (await note.innerText()).trim() !== '')
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem })
    await page.close()

    // Another tab settles the deadline; a save fails and is retried.
    const records = await context.newPage(), peer = await context.newPage()
    for (const tabPage of [records, peer]) { await tabPage.goto(url); await button('开始专注', tabPage).waitFor() }
    await button('开始专注', peer).click()
    await button('暂停专注', peer).waitFor()
    const recordsBanner = records.locator('.timer-ended'), recordsLive = records.locator('.app > [aria-live]')
    await records.locator('.tab-bar').getByRole('button', { name: '记录', exact: true }).click()
    await records.locator('.records-status-button').getByText('专注计时').waitFor()
    await button('结束专注', peer).click()
    await button('确认结束', peer.getByRole('dialog')).click()
    await button('开始休息', peer).waitFor()
    await records.locator('.records-status-button').getByText('计时结束').waitFor()
    check('A manual end in another tab raises no banner', !await recordsBanner.count())
    await button('准备专注', peer).click()

    await button('开始专注', peer).click()
    await button('暂停专注', peer).waitFor()
    await records.locator('.records-status-button').getByText('专注计时').waitFor()
    const peerSession = await peer.evaluate(() => JSON.parse(localStorage.getItem('whale-focus:snapshot')).timer.session)
    await context.clock.fastForward(peerSession.durationMs + 100)
    await context.clock.runFor(500)
    await recordsBanner.waitFor()
    check('A deadline settled by either tab raises the banner', (await recordsBanner.innerText()).includes('这一段计时结束了'))
    check('The shared live region announces that ending', (await recordsLive.innerText()).includes('这一段计时结束了'))
    await button('查看结果', recordsBanner).click()
    await button('开始休息', records).waitFor()
    await peer.close()

    await button('准备专注', records).click()
    await button('开始专注', records).click()
    await button('暂停专注', records).waitFor()
    await records.locator('.tab-bar').getByRole('button', { name: '记录', exact: true }).click()
    const failing = await records.evaluate(() => {
      window.originalSetItem = Storage.prototype.setItem
      Storage.prototype.setItem = function (name, value) {
        if (name === 'whale-focus:snapshot') throw new DOMException('Injected quota failure', 'QuotaExceededError')
        return window.originalSetItem.call(this, name, value)
      }
      return JSON.parse(localStorage.getItem('whale-focus:snapshot')).timer.session
    })
    await context.clock.fastForward(failing.durationMs + 100)
    await context.clock.runFor(500)
    await recordsBanner.waitFor()
    check('A failed save says so in the banner and the announcement', (await recordsBanner.innerText()).includes('尚未保存') && (await recordsLive.innerText()).includes('尚未保存'))
    await records.evaluate(() => { Storage.prototype.setItem = window.originalSetItem })
    await records.locator('.records-status-button').click()
    await button('重试保存', records.getByRole('dialog')).click()
    await recordsBanner.getByText('已保存', { exact: false }).waitFor()
    await records.keyboard.press('Escape')
    check('A successful retry updates the banner and the announcement together', (await recordsLive.innerText()).includes('已保存') && !(await recordsLive.innerText()).includes('尚未保存'))
    check('Timer notices produce no unexpected browser errors', errors.filter(text => !text.includes('Injected quota')).length === 0)
  } finally { await context.close() }
}
