import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { nowMs } from '../../adapters/calendar'
import { newId } from '../../adapters/ids'
import { feedbackCatalog } from '../../data/encouragement'
import { sceneNoticeDelayMs, sceneUnlockText } from '../../data/scene-copy'
import { createFeedbackHost, feedbackSignature, interactWithFeedback, updateFeedbackHost, type FeedbackHostInput } from '../../logic/feedback-host'
import type { AskPool } from '../../logic/feedback'
import { companionSceneOf, companionViewOf } from '../../logic/presentation'
import { pendingSceneAnnouncement } from '../../logic/scenes'
import type { ClockApp } from '../useClockApp'

/**
 * Mount above navigation. No copy or animation event is generated by countdown ticks.
 * Event encouragement follows the saved preference unless overridden; explicit requests always work.
 */
export function useFeedback(app: ClockApp, options: { active?: boolean; nodeEncouragement?: boolean; completedProgress?: number; allowSceneNotice?: boolean } = {}) {
  const [pageVisible, setPageVisible] = useState(() => typeof document === 'undefined' || !document.hidden)
  const [editing, setEditing] = useState(false)
  useEffect(() => {
    const visible = () => setPageVisible(!document.hidden)
    const input = () => setEditing(Boolean(document.activeElement?.matches('input, textarea, [contenteditable="true"]')))
    document.addEventListener('visibilitychange', visible)
    document.addEventListener('focusin', input)
    document.addEventListener('focusout', input)
    return () => {
      document.removeEventListener('visibilitychange', visible)
      document.removeEventListener('focusin', input)
      document.removeEventListener('focusout', input)
    }
  }, [])
  const input: FeedbackHostInput = {
    snapshot: app.snapshot, persistence: app.saveState, event: app.feedbackEvent,
    active: (options.active ?? true) && pageVisible, nodeEncouragement: options.nodeEncouragement ?? app.snapshot.settings.encouragementEnabled,
  }
  const [stored, setStored] = useState(() => createFeedbackHost(input, feedbackCatalog))
  // Adjusting local state during render prevents a stale success frame being painted after a
  // failed write or phase change. The signature guard settles in one immediate rerender.
  const state = stored.signature === feedbackSignature(input) ? stored : updateFeedbackHost(stored, input, feedbackCatalog)
  if (state !== stored) setStored(state)

  const [sceneNotice, setSceneNotice] = useState<ClockApp['sceneAnnouncement']>(null)
  const [handledClaim, setHandledClaim] = useState<string | null>(null)
  const quiet = input.active && !editing && options.allowSceneNotice !== false &&
    !app.snapshot.timer.session && app.saveState === 'saved' && state.feedback.frame.status.kind !== 'error'
  const claimed = app.sceneAnnouncement
  if (claimed && claimed.id !== handledClaim) {
    setHandledClaim(claimed.id)
    setSceneNotice(quiet && claimed.generation === app.snapshot.datasetGeneration ? claimed : null)
  }
  if (sceneNotice && (!quiet || !claimed || sceneNotice.generation !== app.snapshot.datasetGeneration)) setSceneNotice(null)
  const notice = quiet && claimed && sceneNotice?.generation === app.snapshot.datasetGeneration ? sceneNotice : null
  const pendingScene = pendingSceneAnnouncement(app.snapshot.scenes)
  const attemptedClaim = useRef<string | null>(null)
  useEffect(() => {
    if (!quiet || notice || !pendingScene) return
    const key = `${app.snapshot.datasetGeneration}:${pendingScene}`
    if (attemptedClaim.current === key) return
    // A fixed quiet interval lets an ending settle; no animation callback gates
    // the claim or any user action. Navigation, typing and new starts cancel it.
    const timer = window.setTimeout(() => {
      if (document.hidden) return
      attemptedClaim.current = key
      app.dispatch({ type: 'claimSceneAnnouncement', sceneId: pendingScene })
    }, sceneNoticeDelayMs)
    return () => window.clearTimeout(timer)
  }, [quiet, notice, pendingScene, app.snapshot.datasetGeneration, app.dispatch])

  const request = useCallback((category?: AskPool) => {
    setSceneNotice(null)
    const event = { kind: 'encouragement-requested' as const, id: newId(), atMs: nowMs(), origin: 'user' as const, ...(category ? { category } : {}) }
    setStored(previous => interactWithFeedback(previous, input, event, feedbackCatalog))
  }, [input.snapshot, input.persistence, input.event, input.active, input.nodeEncouragement])
  const next = useCallback(() => {
    const pool = state.feedback.frame.encouragement?.pool
    request(state.feedback.frame.placement === 'requested' && pool?.startsWith('ASK') ? pool as AskPool : undefined)
  }, [request, state.feedback.frame])
  const dismiss = useCallback(() => {
    const event = { kind: 'dismissed' as const, id: newId(), atMs: nowMs(), origin: 'user' as const }
    setStored(previous => interactWithFeedback(previous, input, event, feedbackCatalog))
  }, [input.snapshot, input.persistence, input.event, input.active, input.nodeEncouragement])

  const view = companionViewOf(state.feedback.frame, { motionEnabled: app.snapshot.settings.motionEnabled, encouragementEnabled: app.snapshot.settings.encouragementEnabled })
  const scene = useMemo(() => companionSceneOf(app.snapshot, state.cue, {
    completedProgress: options.completedProgress ?? 0, visible: input.active,
    persistence: app.saveState, hasError: view.hasError,
  }), [app.snapshot, state.cue, options.completedProgress, input.active, app.saveState, view.hasError])
  const feedback = notice ? { ...state.feedback, announcement: {
    id: `scene-unlock:${notice.generation}:${notice.sceneId}`, text: sceneUnlockText(notice.sceneId), priority: 'polite' as const,
  } } : state.feedback
  // `cue` has its own identity; it is not derived from the screen-reader announcement.
  return { feedback, view, scene, cue: state.cue, request, next, dismiss,
    sceneNotice: notice ? sceneUnlockText(notice.sceneId) : null, dismissSceneNotice: () => setSceneNotice(null) }
}
